// 带变量的后端消息（正则 + 取值函数）
const EN_PATTERNS = [
  [/^(.+?)上传已达上限 (\d+) 张，请稍后再试或联系管理员$/, m => `${t(m[1])} upload limit reached (${m[2]}). Try later or ask the administrator.`],
  [/^超过单图上限 (\d+)MB$/, m => `Exceeds the per-image limit of ${m[1]} MB`],
  [/^quota exceeded \(left (\d+) KB\)$/, m => `Quota exceeded (${m[1]} KB left)`],
]

// 菜单项 label 形如「🏷️ 站点与外观」：表里存的是去 emoji 的键，命中后把 emoji 拼回去
const EMOJI_PREFIX = /^([\p{Extended_Pictographic}\uFE0F\u200D]+\s*)([\s\S]+)$/u

export function t(s) {
  if (i18n.lang === 'zh' || typeof s !== 'string') return s
  if (EN[s]) return EN[s]
  // 组合值（如后端归属地「局域网 / 本机」）：逐段查表，全部命中才替换
  if (s.includes(' / ')) {
    const parts = s.split(' / ')
    if (parts.every(x => EN[x])) return parts.map(x => EN[x]).join(' / ')
  }
  const m = s.match(EMOJI_PREFIX)
  if (m && EN[m[2]]) return m[1] + EN[m[2]]
  for (const [re, fn] of EN_PATTERNS) {
    const hit = s.match(re)
    if (hit) return fn(hit)
  }
  return s
}

export function setLang(l) {
  i18n.lang = l
  localStorage.setItem('lg_lang', l)
  document.documentElement.lang = l === 'zh' ? 'zh-CN' : 'en'
}

